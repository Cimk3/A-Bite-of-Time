/** Generate shelf-fit data from the emitted 0.9.5 food meshes, reused in 0.9.6. */
import {readFileSync,writeFileSync} from 'node:fs';
import {dishes,servingKey} from '../.build/catalog.js';
import {modelBounds} from './detail-art.mjs';

const read=path=>JSON.parse(readFileSync(path,'utf8'));
const measurements={},root=process.argv[2]??'packs/FoodAndTable_RP';
for(const food of dishes){
 const key=servingKey(food,food.vessel);
 const path=root+'/models/entity/mcpe_food/surface_'+key+'.geo.json';
 const geo=read(path)['minecraft:geometry'][0];
 const {low,high}=modelBounds(geo.bones.flatMap(b=>b.cubes??[]));
 measurements['mcpe_food:'+food.key]=[...low,...high].map(v=>Math.round(v*1e6)/1e6);
}
const source='// Generated by tools/capture-pastry-bounds.mjs from food mesh bounds.\n'+
 'export const pastryBounds:Partial<Record<string, readonly [number,number,number,number,number,number]>> = '+'{\n'+Object.entries(measurements).map(([key,value])=>' '+JSON.stringify(key)+': '+JSON.stringify(value)).join(',\n')+'\n}'+';\n';
writeFileSync('src/generated-pastry-bounds.ts',source,'utf8');
console.log('Captured',Object.keys(measurements).length,'food bounds');
